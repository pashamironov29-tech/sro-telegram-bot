# -*- coding: utf-8 -*-
"""Отчёт: зачем бот членам и кандидатам в регионах. python build_otchet_regiony_docx.py"""

from datetime import date
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Cm, Pt, RGBColor
from docx.oxml.ns import qn

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "OTCHET_ZACHEM_BOT_REGIONY.docx"


def setup(doc: Document) -> None:
    s = doc.sections[0]
    s.top_margin = Cm(2)
    s.bottom_margin = Cm(2)
    s.left_margin = Cm(2.5)
    s.right_margin = Cm(1.5)
    st = doc.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(12)
    st._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")


def h(doc, text, level=1):
    doc.add_heading(text, level=level)


def p(doc, text):
    para = doc.add_paragraph(text)
    para.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY


def li(doc, text):
    doc.add_paragraph(text, style="List Bullet")


def table(doc, headers, rows):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = "Table Grid"
    for i, hd in enumerate(headers):
        t.rows[0].cells[i].text = hd
        for par in t.rows[0].cells[i].paragraphs:
            for r in par.runs:
                r.bold = True
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            t.rows[ri + 1].cells[ci].text = val
    doc.add_paragraph()


def main():
    doc = Document()
    setup(doc)

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = title.add_run(
        "Зачем Telegram-бот СРО «ГЕН»\n"
        "членам и вступающим организациям в регионах\n"
        "(в том числе Дальний Восток и другие часовые пояса)"
    )
    r.bold = True
    r.font.size = Pt(15)

    sub = doc.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub.add_run(f"Дата: {date.today().strftime('%d.%m.%Y')}").font.size = Pt(11)

    doc.add_paragraph()
    p(
        doc,
        "Ассоциация «ГЕН» работает из Москвы (UTC+3). Большая часть членов СРО — "
        "компании по всей России: Дальний Восток, Сибирь, Урал, юг. У них другой "
        "рабочий день, другой ритм и не всегда возможность дозвониться «пока у вас "
        "день в офисе». Telegram-бот — это не замена специалистам, а круглосуточный "
        "помощник, который ведёт к официальным материалам на srogen.ru и снимает "
        "типовые вопросы без ожидания на линии.",
    )

    doc.add_page_break()

    h(doc, "1. Проблема: «у нас уже вечер, у вас ещё нет»")
    p(
        doc,
        "Пример: компания во Владивостоке (UTC+10). Когда в Москве 10:00 и аппарат "
        "только разбирает почту, на Дальнем Востоке уже 17:00 — конец рабочего дня. "
        "Когда в Москве 17:00 и можно позвонить «после обеда», во Владивостоке 00:00 — "
        "сотрудник не будет звонить в Ассоциацию.",
    )
    table(
        doc,
        ["Город (пример)", "Смещение от Москвы", "Когда в Москве 10:00–18:00"],
        [
            ["Владивосток", "+7 ч", "17:00–01:00 (ночь)"],
            ["Хабаровск", "+7 ч", "17:00–01:00"],
            ["Якутск", "+6 ч", "16:00–00:00"],
            ["Красноярск", "+4 ч", "14:00–22:00"],
            ["Екатеринбург", "+2 ч", "12:00–20:00"],
        ],
    )
    p(
        doc,
        "Итог: вступающая или действующая организация откладывает вопрос «на завтра», "
        "теряет время на вступление, подготовку к проверке или кадровые решения. "
        "Часть обращений вообще не доходит — человек ищет ответ на сайте и бросает, "
        "если структура непонятна с первого экрана.",
    )

    h(doc, "2. Что даёт бот — простыми словами")
    li(doc, "Работает в Telegram **круглосуточно** — когда у пользователя есть 10 минут, а не «когда совпало с Москвой».")
    li(doc, "Отвечает **типовыми блоками**: как вступить, какие взносы, какие документы, НОК/НРС, бланки.")
    li(doc, "Ведёт **на официальный сайт** — бот не «придумывает» нормы, а показывает, где лежит ответ и форма.")
    li(doc, "Для действующих членов — **поиск по ИНН**, месяц из плана проверок, **скачивание бланков** в чате.")
    li(doc, "Телефон и e-mail Ассоциации всегда в ответе, если нужен живой специалист.")

