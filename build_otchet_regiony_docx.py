    p(
        doc,
        "Региональным компаниям часто нужны не только «ГЕН», но и партнёрское СРО, "
        "НОСТРОЙ, НОПРИЗ. В боте — раздел «Партнёры и НО» и поиск по названию "
        "(«мотс», «нострой») без ручного поиска по сайту.",
    )

