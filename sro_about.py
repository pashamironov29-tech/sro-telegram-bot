def rewrite_srogen_path_for_sro(sro_id: str | None, path: str) -> str:
    """
    Переписать путь с сайта ОГПС под структуру выбранного СРО.
    /vstuplenie_v_sro/... → /vstuplenie/... у всех, кроме ОГПС.
    """
    if not path:
        return path
    p = path if path.startswith("/") else f"/{path}"
    sid = sro_id or "OGPS"
    if p.startswith("/vstuplenie_v_sro"):
        rest = p[len("/vstuplenie_v_sro") :]
        return join_section_prefix_for_sro(sid) + rest
    return p


