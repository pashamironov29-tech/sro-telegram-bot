def _contacts_block(sro_id: str) -> str:
    data = SRO_CONTACTS.get(sro_id) or {}
    lines_out: list[str] = []
    for row in data.get("lines") or []:
        val = (row.get("value") or "").strip()
        if not val:
            continue
        label = row.get("label")
        if label:
            lines_out.append(f"📞 {label}: <code>{val}</code>")
        else:
            lines_out.append(f"📞 <code>{val}</code>")
    email = (data.get("email") or "").strip()
    if email:
        lines_out.append(f"📧 Email: <code>{email}</code>")
    return "\n".join(lines_out)


def format_about_association(sro_id: str | None) -> str:
    """HTML-текст для кнопки «Об Ассоциации СРО»."""
    sid = sro_id or "OGPS"
    profile = get_sro_profile(sid) or get_sro_profile("OGPS") or {}
    custom = _ABOUT.get(sid)
    about_url = about_url_for_sro(sid)

    if custom:
        title = custom["title"]
        body = custom["body"]
        address = custom.get("address")
    else:
        name = profile.get("short_title") or sro_display_name(sid) or sid
        act = ACTIVITY_LABEL.get(profile.get("activity") or "", "")
        title = f"{name}" + (f" ({act})" if act else "")
        body = (
            f"Партнёрская саморегулируемая организация "
            f"<b>{sro_display_name(sid) or name}</b>.\n\n"
            "Подробная информация об ассоциации, вступлении и контроле — "
            "на официальном сайте.\n\n"
            "📊 По ФЗ № 124-ФЗ для строительства: при договоре до "
            "<code>10 000 000</code> ₽ членство в СРО может не требоваться; "
            "выше — уточняйте требования."
        )
        address = None

    parts = [f"🏢 <b>{title}</b>\n\n{body}"]

    contacts = _contacts_block(sid)
    if address or contacts:
        parts.append("\n\n📍 <b>Контакты:</b>")
        if address:
            parts.append(f"\n🏢 Адрес: <code>{address}</code>")
        if contacts:
            parts.append("\n" + contacts)

    parts.append(
        f"\n\n🌐 <b>О ассоциации на сайте:</b> {about_url}\n"
        f"<i>Открыть можно по ссылке. Контакты копируются из чата.</i>"
    )
    if sid != "OGPS":
        parts.append(
            "\n\n<i>Сейчас контекст: это СРО, не ОГПС. "
            "Сменить — ИНН или «Назад к выбору организации».</i>"
        )
    return "".join(parts)
