from __future__ import annotations

# ИНН можно проверить в боте поиском — статус «Член СРО» в реестре
FEATURED_MEMBERS: list[dict[str, str]] = [
    {
        "name": "АО «Мосметрострой»",
        "inn": "7710068052",
        "note": "инфраструктура и метрострой",
    },
    {
        "name": "ООО «Самолет Девелопмент»",
        "inn": "7723844961",
        "note": "девелопмент",
    },
    {
        "name": "ООО «РусГидроПроект»",
        "inn": "7722315041",
        "note": "проектирование",
    },
    {
        "name": "ООО «ПИК»",
        "inn": "9102205130",
        "note": "девелопмент · СРО МОТС",
    },
]

REESTR_STATS_LINE = (
    "В реестрах <b>15 СРО</b> экосистемы Ассоциации «ГЕН» — "
    "<b>более 18 000</b> организаций (строители, проектировщики, изыскания)."
)

TRUSTED_BUTTON = "⭐ Нам доверяют"


def format_trusted_members_message() -> str:
    lines = [
        "⭐ <b>Крупные и известные компании в СРО Ассоциации</b>",
        "",
        REESTR_STATS_LINE,
        "",
        "Среди действующих и бывших членов экосистемы — федеральные подрядчики "
        "и девелоперы. Несколько примеров (актуальность статуса — в реестре):",
        "",
    ]
    for item in FEATURED_MEMBERS:
        inn = item["inn"]
        name = item["name"]
        note = item.get("note")
        tail = f" — <i>{note}</i>" if note else ""
        lines.append(f"• <b>{name}</b>{tail}\n  ИНН: <code>{inn}</code>")
    lines.extend(
        [
            "",
            "🔍 <b>Проверить любую организацию:</b> отправьте ИНН или название в чат — "
            "бот покажет членство по всем СРО экосистемы.",
            "",
            "<i>Список не исчерпывающий. Полные реестры — на сайтах srogen.ru и партнёрских СРО.</i>",
        ]
    )
    return "\n".join(lines)


def trusted_members_welcome_snippet() -> str:
    names = ", ".join(m["name"] for m in FEATURED_MEMBERS[:3])
    return (
        f"\n\n⭐ <b>Нам доверяют крупные игроки отрасли</b> — среди членов экосистемы, "
        f"например: {names} и тысячи других компаний. "
        f"Подробнее: <b>{TRUSTED_BUTTON}</b> в разделе «Ассоциация и партнёры»."
    )
