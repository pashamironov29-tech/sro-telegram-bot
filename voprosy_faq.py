def get_voprosy_site_item(topic_id: str):
    label = VOPROSY_SITE_ITEM_MAP.get(topic_id)
    if not label or label.startswith("__"):
        return None
    return get_voprosy_item_by_label(label)


def list_voprosy_site_topics(
    section_id: str,
    activity: str | None = None,
) -> list[tuple[str, str]]:
    """
    Темы раздела: (topic_id, текст кнопки).
    topic_id стабильный — подписи кнопок можно менять в VOPROSY_SITE_SECTIONS.
    """
    section = get_voprosy_site_section(section_id)
    if not section:
        return []
    out: list[tuple[str, str]] = []
    for topic_id, button in section["items"]:
        if topic_id == "membership_terms":
            out.append((topic_id, button))
            continue
        item = get_voprosy_site_item(topic_id)
        if not item:
            continue
        if activity and not activity_allows_scopes(activity, _item_scopes(item)):
            continue
        out.append((topic_id, button))
    return out


def build_voprosy_site_button_maps(
    activity: str | None = None,
) -> tuple[dict[str, str], dict[str, str]]:
    """button_text -> section_id / topic_id (по актуальным подписям)."""
    section_map: dict[str, str] = {}
    topic_map: dict[str, str] = {}
    for section in VOPROSY_SITE_SECTIONS:
        topics = list_voprosy_site_topics(section["id"], activity=activity)
        if activity and not topics:
            continue
        section_map[section["button"]] = section["id"]
        for topic_id, button in topics:
            topic_map[button] = topic_id
    return section_map, topic_map


