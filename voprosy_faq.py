def _normalize(text: str) -> str:
    text = text.lower().replace("ё", "e")
    return re.sub(r"\s+", " ", text.strip())


def _item_scopes(item: dict) -> list[str]:
    return item.get("scopes", ["common"])


def detect_question_activity_bias(question: str) -> str | None:
    normalized = _normalize(question)
    if "проектн" in normalized and ("документ" in normalized or "документац" in normalized):
        return "proekt"
    if "проектиров" in normalized:
        return "proekt"
    if any(x in normalized for x in ("генподряд", "субподряд")):
        return "stroy"
    if "строительн" in normalized and "контрол" in normalized:
        return "stroy"
    if "обследован" in normalized and "конструкц" in normalized:
        return "izysk"
    if "изыскан" in normalized:
        return "izysk"
    return None


def _score_item(normalized: str, item: dict) -> tuple[float, int]:
    score = 0.0
    hits = 0
    for phrase in item.get("phrases", ()):
        if phrase in normalized:
            score = max(score, 0.95)
    hits = sum(1 for kw in item["keywords"] if kw in normalized)
    min_hits = item.get("min_hits", 2)
    if hits >= min_hits:
        score = max(score, 0.75 + hits / max(len(item["keywords"]), 1) * 0.25)
    elif hits >= 1 and any(
        p in normalized
        for p in ("что такое", "что это", "чем является", "объясни", "расскажи")
    ):
        score = max(score, 0.82)
    else:
        score = max(score, SequenceMatcher(None, normalized, _normalize(item["label"])).ratio())
    return score, hits


def match_voprosy_faq(question: str, min_ratio: float = 0.52, activity: str | None = None):
    normalized = _normalize(question)
    best_item = None
    best_score = 0.0
    best_hits = 0
    best_blocked = None
    best_blocked_score = 0.0

    for item in VOPROSY_ITEMS:
        score, hits = _score_item(normalized, item)
        if score < min_ratio:
            continue
        scopes = _item_scopes(item)
        if activity and not activity_allows_scopes(activity, scopes):
            if score > best_blocked_score:
                best_blocked = item
                best_blocked_score = score
            continue
        if score > best_score or (score == best_score and hits > best_hits):
            best_score = score
            best_hits = hits
            best_item = item

    if best_item:
        return best_item
    if best_blocked and best_blocked_score >= min_ratio:
        return {"_scope_blocked": True, "item": best_blocked}
    return None


def format_scope_mismatch_response(question: str, user_activity: str, blocked_item: dict) -> dict:
    need_scopes = _item_scopes(blocked_item)
    need = need_scopes[0] if need_scopes and need_scopes != ["common"] else "proekt"
    if "proekt" in need_scopes:
        need = "proekt"
    elif "izysk" in need_scopes:
        need = "izysk"
    elif "stroy" in need_scopes:
        need = "stroy"
    hint = {
        "proekt": "проектировщиков (например, ОГПП)",
        "stroy": "строителей (например, ОСО, ГЕН)",
        "izysk": "изыскателей",
    }.get(need, "другого типа СРО")
    user_label = ACTIVITY_LABEL.get(user_activity, user_activity)
    return {
        "ok": True,
        "text": (
            f"🤖 По вопросу «<b>{question}</b>»:\n\n"
            f"⚠️ Сейчас контекст: <b>{user_label}</b>. "
            f"Этот вопрос относится к СРО <b>{hint}</b>.\n\n"
            "Введите <b>ИНН</b> организации в нужном СРО или нажмите кнопку "
            f"«{CTX_BUTTON_PREFIX}…» после карточки компании.\n\n"
            "<i>Общие вопросы (налоги, Федресурс, взносы) можно задавать в любом контексте.</i>"
        ),
    }


